CREATE PACKAGE PKG_ORDERS
AS
BEGIN
  FUNCTION TOTAL_FOR (A_CUSTOMER_ID INTEGER) RETURNS NUMERIC(12,2);
END^

CREATE PACKAGE BODY PKG_ORDERS
AS
BEGIN
  FUNCTION TOTAL_FOR (A_CUSTOMER_ID INTEGER) RETURNS NUMERIC(12,2)
  AS
  BEGIN
    RETURN (SELECT SUM(TOTAL) FROM ORDERS WHERE CUSTOMER_ID = :A_CUSTOMER_ID);
  END
END^
