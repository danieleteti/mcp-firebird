CREATE PROCEDURE SP_CUSTOMER_TOTAL (A_CUSTOMER_ID INTEGER)
RETURNS (TOTAL_SPENT NUMERIC(12,2))
AS
BEGIN
  SELECT SUM(TOTAL) FROM ORDERS WHERE CUSTOMER_ID = :A_CUSTOMER_ID
    INTO :TOTAL_SPENT;
  SUSPEND;
END^

CREATE TRIGGER TR_ORDERS_BI FOR ORDERS
ACTIVE BEFORE INSERT POSITION 0
AS
BEGIN
  IF (NEW.TOTAL IS NULL) THEN NEW.TOTAL = 0;
END^
